    #[test]
    fn geometry_publication_replaces_only_an_owned_tree() {
        let output = tempfile::tempdir().unwrap();
        let destination = output.path().join("geometries");
        fs::create_dir(&destination).unwrap();
        fs::write(destination.join("user-file"), "keep").unwrap();
        let unowned_stage = tempfile::TempDir::new_in(output.path()).unwrap();
        assert!(publish_geometry_tree(output.path(), unowned_stage).is_err());
        assert!(destination.join("user-file").is_file());

        fs::write(destination.join(".seqproc-generated"), "owned").unwrap();
        let owned_stage = tempfile::TempDir::new_in(output.path()).unwrap();
        fs::write(owned_stage.path().join(".seqproc-generated"), "owned").unwrap();
        fs::write(owned_stage.path().join("new.geom"), "header { efgdl = 2 }").unwrap();
        publish_geometry_tree(output.path(), owned_stage).unwrap();
        assert!(!destination.join("user-file").exists());
        assert!(destination.join("new.geom").is_file());
    }
